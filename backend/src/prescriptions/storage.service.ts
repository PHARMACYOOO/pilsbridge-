import { Injectable } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

export const UPLOAD_TYPES = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
  'application/pdf': 'pdf',
} as const;
export type UploadType = keyof typeof UPLOAD_TYPES;

/** Kept apart so a key from one area can never be read through another's endpoint. */
export type StorageFolder = 'prescriptions' | 'compliance';

/** Identify a file by its first bytes, not by the client-supplied content type. */
export function sniff(buf: Buffer): UploadType | null {
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return 'image/jpeg';
  if (buf.length >= 8 && buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return 'image/png';
  if (buf.length >= 12 && buf.toString('ascii', 0, 4) === 'RIFF' && buf.toString('ascii', 8, 12) === 'WEBP') return 'image/webp';
  if (buf.length >= 5 && buf.toString('ascii', 0, 5) === '%PDF-') return 'application/pdf';
  return null;
}

/**
 * Local-disk storage for development. Production should swap this for encrypted S3-compatible
 * storage with short-lived signed URLs; callers only depend on save/read by opaque key.
 */
@Injectable()
export class StorageService {
  private readonly root: string;

  constructor(config: ConfigService) {
    this.root = resolve(config.get<string>('UPLOAD_DIR') ?? './uploads');
  }

  async save(buf: Buffer, type: UploadType, folder: StorageFolder = 'prescriptions'): Promise<string> {
    const key = `${folder}/${randomUUID()}.${UPLOAD_TYPES[type]}`;
    await mkdir(join(this.root, folder), { recursive: true });
    await writeFile(join(this.root, key), buf, { mode: 0o600 });
    return key;
  }

  async read(key: string, folder: StorageFolder = 'prescriptions'): Promise<Buffer> {
    // Keys are generated by save(); reject anything that could escape the upload root or its folder.
    if (!new RegExp(`^${folder}/[0-9a-f-]{36}\\.(jpg|png|webp|pdf)$`).test(key)) throw new Error('Invalid storage key');
    return readFile(join(this.root, key));
  }
}
